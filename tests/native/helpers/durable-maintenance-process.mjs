import '../../util/config.js';
import fs from 'node:fs';
import { FsEngine } from '../../../src/storage/engines/fs-engine.js';
import { services } from './session-fixture.js';
import { maintainSession } from '../../../src/native/session-maintenance.js';
const input = JSON.parse(fs.readFileSync(process.argv[2], 'utf8'));
const engine = new FsEngine({ directoriesByHandle: () => input.dirs });
const f = services(input, engine);
await f.core.load(input.handle, input.sessionId);
engine._durabilityFault = point => { if (point === input.stage) process.exit(72); };
await maintainSession(f.sessionRepo, input.handle, input.sessionId, { now: input.now, batchSize: 1 });
